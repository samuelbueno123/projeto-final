-- V17: 10 Funcionalidades Competitivas de Gestão Condominial
-- 1. Obras e Reformas (NBR 16.280)
CREATE TABLE IF NOT EXISTS tb_renovation_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES tb_unit(id) ON DELETE CASCADE,
    requester_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(1000),
    art_rrt_number VARCHAR(100),
    contractor_name VARCHAR(160),
    contractor_phone VARCHAR(40),
    start_date DATE NOT NULL,
    expected_end_date DATE NOT NULL,
    actual_end_date DATE,
    noise_level VARCHAR(30) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    decision_notes VARCHAR(1000),
    decided_by_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    decided_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_renovation_condo ON tb_renovation_request(condominium_id, status);
CREATE INDEX IF NOT EXISTS idx_renovation_unit ON tb_renovation_request(unit_id);

-- 2. Livro Digital de Passagem de Turno da Portaria
CREATE TABLE IF NOT EXISTS tb_concierge_shift_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    outgoing_doorman_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    incoming_doorman_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    shift_type VARCHAR(30) NOT NULL,
    shift_date DATE NOT NULL,
    gate_status VARCHAR(30) NOT NULL DEFAULT 'ALL_NORMAL',
    pending_keys_count INTEGER NOT NULL DEFAULT 0,
    pending_packages_count INTEGER NOT NULL DEFAULT 0,
    occurrences_summary VARCHAR(1500),
    general_notes VARCHAR(1500),
    acknowledged_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_shift_condo ON tb_concierge_shift_log(condominium_id, shift_date DESC);

-- 3. Controle de Chaves Físicas e Tags de Acesso da Portaria
CREATE TABLE IF NOT EXISTS tb_key_registry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    key_code VARCHAR(50) NOT NULL,
    description VARCHAR(200) NOT NULL,
    key_category VARCHAR(40) NOT NULL DEFAULT 'COMMON_AREA',
    current_status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    borrower_name VARCHAR(150),
    borrower_document VARCHAR(40),
    borrower_phone VARCHAR(40),
    unit_id BIGINT REFERENCES tb_unit(id) ON DELETE SET NULL,
    borrowed_at TIMESTAMP(6),
    expected_return_at TIMESTAMP(6),
    returned_at TIMESTAMP(6),
    checked_out_by_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    checked_in_by_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_key_condo ON tb_key_registry(condominium_id, current_status);

-- 4. Botão de Pânico & Alerta de Emergência Condominial
CREATE TABLE IF NOT EXISTS tb_emergency_alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    unit_id BIGINT REFERENCES tb_unit(id) ON DELETE SET NULL,
    resident_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    emergency_type VARCHAR(40) NOT NULL,
    details VARCHAR(1000),
    contact_phone VARCHAR(40),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    attended_by_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    resolution_notes VARCHAR(1000),
    attended_at TIMESTAMP(6),
    resolved_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_emergency_condo ON tb_emergency_alert(condominium_id, status);

-- 5. Previsão Orçamentária por Categoria
CREATE TABLE IF NOT EXISTS tb_budget_forecast (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    year INTEGER NOT NULL,
    month INTEGER NOT NULL,
    category VARCHAR(60) NOT NULL,
    budgeted_amount NUMERIC(12,2) NOT NULL,
    notes VARCHAR(500),
    created_by_id BIGINT NOT REFERENCES tb_user(id) ON DELETE SET NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_budget_condo_year_month_cat UNIQUE (condominium_id, year, month, category)
);

-- 6. Medição Individualizada de Água e Gás
CREATE TABLE IF NOT EXISTS tb_utility_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES tb_unit(id) ON DELETE CASCADE,
    utility_type VARCHAR(30) NOT NULL,
    year INTEGER NOT NULL,
    month INTEGER NOT NULL,
    reading_date DATE NOT NULL,
    current_reading NUMERIC(10,3) NOT NULL,
    previous_reading NUMERIC(10,3) NOT NULL,
    consumption NUMERIC(10,3) NOT NULL,
    leak_suspicion BOOLEAN NOT NULL DEFAULT FALSE,
    meter_photo_url TEXT,
    reader_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_utility_unit_year_month_type UNIQUE (unit_id, year, month, utility_type)
);

CREATE INDEX IF NOT EXISTS idx_utility_condo ON tb_utility_reading(condominium_id, year, month);

-- 7. Inspeção Predial Periódica / Checklist de Manutenção Preventiva
CREATE TABLE IF NOT EXISTS tb_maintenance_checklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    frequency VARCHAR(30) NOT NULL DEFAULT 'MONTHLY',
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    inspected_at TIMESTAMP(6),
    inspector_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL,
    general_notes VARCHAR(1000),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tb_maintenance_checklist_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id BIGINT NOT NULL REFERENCES tb_maintenance_checklist(id) ON DELETE CASCADE,
    item_description VARCHAR(250) NOT NULL,
    area_or_location VARCHAR(150),
    status VARCHAR(30) NOT NULL DEFAULT 'CONFORMING',
    observation VARCHAR(500),
    equipment_id BIGINT REFERENCES tb_maintenance_equipment(id) ON DELETE SET NULL
);

-- 8. Gestão de Contratos de Prestação de Serviços e Garantias
CREATE TABLE IF NOT EXISTS tb_service_contract (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    supplier_id BIGINT REFERENCES tb_supplier(id) ON DELETE SET NULL,
    title VARCHAR(180) NOT NULL,
    contract_number VARCHAR(80),
    category VARCHAR(60) NOT NULL,
    monthly_value NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    auto_renew BOOLEAN NOT NULL DEFAULT FALSE,
    renewal_notice_days INTEGER NOT NULL DEFAULT 30,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    coverage_description VARCHAR(1000),
    document_url TEXT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_contract_condo ON tb_service_contract(condominium_id, status);
