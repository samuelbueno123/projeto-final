-- V16: Auditoria de Segurança, 10 Funcionalidades Comerciais e Otimizações de Índices

-- 1. Reservas e Áreas Comuns (Lista de Espera + Regras de Antecedência, Duração e Frequência)
ALTER TABLE tb_reservation DROP CONSTRAINT IF EXISTS ck_reservation_status;
ALTER TABLE tb_reservation ADD CONSTRAINT ck_reservation_status CHECK (
    status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED', 'COUNTER_PROPOSED', 'WAITLISTED')
);
ALTER TABLE tb_reservation ADD COLUMN IF NOT EXISTS waitlist_position INTEGER;

ALTER TABLE tb_common_area ADD COLUMN IF NOT EXISTS min_advance_hours INTEGER DEFAULT 0;
ALTER TABLE tb_common_area ADD COLUMN IF NOT EXISTS max_advance_days INTEGER DEFAULT 90;
ALTER TABLE tb_common_area ADD COLUMN IF NOT EXISTS max_duration_hours INTEGER DEFAULT 8;
ALTER TABLE tb_common_area ADD COLUMN IF NOT EXISTS max_weekly_bookings_per_user INTEGER DEFAULT 3;
ALTER TABLE tb_common_area ADD COLUMN IF NOT EXISTS allow_waitlist BOOLEAN NOT NULL DEFAULT TRUE;

-- 2. Gestão de Veículos e Vagas de Garagem
CREATE TABLE IF NOT EXISTS tb_parking_spot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    unit_id BIGINT REFERENCES tb_unit(id) ON DELETE SET NULL,
    code VARCHAR(40) NOT NULL,
    location_description VARCHAR(150),
    spot_type VARCHAR(30) NOT NULL DEFAULT 'CAR',
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE tb_vehicle ADD COLUMN IF NOT EXISTS parking_spot_id BIGINT REFERENCES tb_parking_spot(id) ON DELETE SET NULL;
ALTER TABLE tb_vehicle ADD COLUMN IF NOT EXISTS rejection_reason VARCHAR(500);

-- 3. Gestão de Animais de Estimação (Censo de Pets aprimorado)
ALTER TABLE tb_pet ADD COLUMN IF NOT EXISTS image_url TEXT;
ALTER TABLE tb_pet ADD COLUMN IF NOT EXISTS last_vaccine_date DATE;
ALTER TABLE tb_pet ADD COLUMN IF NOT EXISTS status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE tb_pet ADD COLUMN IF NOT EXISTS manager_notes VARCHAR(500);

-- 4. Gestão de Fornecedores e Prestadores de Serviço
CREATE TABLE IF NOT EXISTS tb_supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    company_name VARCHAR(160) NOT NULL,
    contact_name VARCHAR(140),
    phone VARCHAR(40),
    email VARCHAR(140),
    document_number VARCHAR(40),
    service_category VARCHAR(60) NOT NULL DEFAULT 'GERAL',
    address VARCHAR(250),
    notes TEXT,
    rating_average NUMERIC(3,2) NOT NULL DEFAULT 0.00,
    rating_count INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Manutenção Preventiva, Cadastro de Equipamentos/Estruturas e Vínculo com Fornecedores
CREATE TABLE IF NOT EXISTS tb_maintenance_equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condominium_id BIGINT NOT NULL REFERENCES tb_condominium(id) ON DELETE CASCADE,
    preferred_supplier_id BIGINT REFERENCES tb_supplier(id) ON DELETE SET NULL,
    name VARCHAR(160) NOT NULL,
    category VARCHAR(60) NOT NULL DEFAULT 'ELEVADORES',
    location VARCHAR(150),
    manufacturer VARCHAR(120),
    model_number VARCHAR(100),
    serial_number VARCHAR(100),
    installed_at DATE,
    recurrence_days INTEGER NOT NULL DEFAULT 90,
    last_maintenance_date DATE,
    next_maintenance_date DATE NOT NULL,
    responsible_name VARCHAR(140),
    status VARCHAR(30) NOT NULL DEFAULT 'OPERATIONAL',
    notes TEXT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE tb_maintenance_order ADD COLUMN IF NOT EXISTS equipment_id BIGINT REFERENCES tb_maintenance_equipment(id) ON DELETE SET NULL;
ALTER TABLE tb_maintenance_order ADD COLUMN IF NOT EXISTS supplier_id BIGINT REFERENCES tb_supplier(id) ON DELETE SET NULL;
ALTER TABLE tb_maintenance_order ADD COLUMN IF NOT EXISTS responsible_name VARCHAR(150);
ALTER TABLE tb_maintenance_order ADD COLUMN IF NOT EXISTS recurrence_days INTEGER;
ALTER TABLE tb_maintenance_order ADD COLUMN IF NOT EXISTS supplier_rating INTEGER;
ALTER TABLE tb_maintenance_order ADD COLUMN IF NOT EXISTS supplier_feedback VARCHAR(500);

-- 6. Assembleias e Votações Digitais (Presença/Quórum, Elegibilidade e Regras)
CREATE TABLE IF NOT EXISTS tb_assembly_participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assembly_id BIGINT NOT NULL REFERENCES tb_condominium_assembly(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    unit_id BIGINT REFERENCES tb_unit(id) ON DELETE SET NULL,
    checked_in_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    proxy_info VARCHAR(250),
    CONSTRAINT uk_assembly_participant_user UNIQUE (assembly_id, user_id)
);

ALTER TABLE tb_condominium_assembly ADD COLUMN IF NOT EXISTS block_delinquent_units BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE tb_condominium_assembly ADD COLUMN IF NOT EXISTS one_vote_per_unit BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE tb_condominium_assembly ADD COLUMN IF NOT EXISTS quorum_minimum_percent INTEGER NOT NULL DEFAULT 0;

ALTER TABLE tb_assembly_topic ADD COLUMN IF NOT EXISTS result_status VARCHAR(30) NOT NULL DEFAULT 'OPEN';

-- 7. Confirmação de Leitura e Segmentação de Comunicados
ALTER TABLE tb_announcement ADD COLUMN IF NOT EXISTS sector_id BIGINT REFERENCES tb_sector(id) ON DELETE SET NULL;
ALTER TABLE tb_announcement ADD COLUMN IF NOT EXISTS target_role VARCHAR(40);

CREATE TABLE IF NOT EXISTS tb_announcement_read (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES tb_announcement(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    unit_id BIGINT REFERENCES tb_unit(id) ON DELETE SET NULL,
    read_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_announcement_read_user UNIQUE (announcement_id, user_id)
);

-- 8. Controle Avançado de Visitantes (Convites com QR Code e Validade Configurável)
ALTER TABLE tb_visitor_access ADD COLUMN IF NOT EXISTS valid_from TIMESTAMP(6);
ALTER TABLE tb_visitor_access ADD COLUMN IF NOT EXISTS valid_until TIMESTAMP(6);
ALTER TABLE tb_visitor_access ADD COLUMN IF NOT EXISTS qr_code_payload VARCHAR(200);
ALTER TABLE tb_visitor_access ADD COLUMN IF NOT EXISTS checked_in_by_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL;
ALTER TABLE tb_visitor_access ADD COLUMN IF NOT EXISTS checked_out_by_id BIGINT REFERENCES tb_user(id) ON DELETE SET NULL;

ALTER TABLE tb_guest_entry ADD COLUMN IF NOT EXISTS checked_out_at TIMESTAMP(6);

-- 9. Achados e Perdidos (Categorias, Fotos e Comunicação entre Envolvidos)
ALTER TABLE tb_lost_found_item ADD COLUMN IF NOT EXISTS category VARCHAR(50) NOT NULL DEFAULT 'OTHER';
ALTER TABLE tb_lost_found_item ADD COLUMN IF NOT EXISTS image_url TEXT;
ALTER TABLE tb_lost_found_item ADD COLUMN IF NOT EXISTS claim_message VARCHAR(500);
ALTER TABLE tb_lost_found_item ADD COLUMN IF NOT EXISTS resolution_notes VARCHAR(500);

CREATE TABLE IF NOT EXISTS tb_lost_found_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES tb_lost_found_item(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    message VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

