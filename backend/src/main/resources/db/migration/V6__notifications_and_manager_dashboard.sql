alter table tb_notification alter column message type text;
alter table tb_notification add column image_url text;
alter table tb_notification drop constraint ck_notification_type;
alter table tb_notification add constraint ck_notification_type check (
    type in ('PACKAGE_RECEIVED', 'PACKAGE_STATUS_CHANGED', 'ANNOUNCEMENT', 'RESERVATION', 'SYSTEM_ANNOUNCEMENT')
);

alter table tb_announcement add column image_url text;

create table tb_unit_payment_status (
    id bigint generated by default as identity primary key,
    unit_id bigint not null unique references tb_unit(id),
    status varchar(30) not null,
    due_date date,
    amount numeric(12,2),
    updated_at timestamp(6) not null,
    updated_by_id bigint not null references tb_user(id),
    constraint ck_unit_payment_status check (status in ('PAID', 'PENDING', 'OVERDUE'))
);
