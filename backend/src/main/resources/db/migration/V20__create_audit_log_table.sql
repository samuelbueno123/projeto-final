-- ============================================================================

CREATE TABLE IF NOT EXISTS tb_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP NOT NULL,
    correlation_id VARCHAR(100),
    category VARCHAR(50) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    principal VARCHAR(180) NOT NULL,
    action VARCHAR(120) NOT NULL,
    resource_type VARCHAR(80),
    resource_id VARCHAR(100),
    condominium_id BIGINT,
    condominium_name VARCHAR(180),
    ip_address VARCHAR(64),
    outcome VARCHAR(30) NOT NULL,
    details VARCHAR(2000)
);

CREATE INDEX IF NOT EXISTS idx_audit_log_timestamp ON tb_audit_log (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_category ON tb_audit_log (category);
CREATE INDEX IF NOT EXISTS idx_audit_log_severity ON tb_audit_log (severity);
CREATE INDEX IF NOT EXISTS idx_audit_log_outcome ON tb_audit_log (outcome);
CREATE INDEX IF NOT EXISTS idx_audit_log_principal ON tb_audit_log (principal);
CREATE INDEX IF NOT EXISTS idx_audit_log_condominium ON tb_audit_log (condominium_id);
