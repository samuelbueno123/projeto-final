create table tb_billing_plan (
                                 id bigint generated by default as identity,
                                 active boolean not null,
                                 monthly_fee numeric(38,2) not null,
                                 name varchar(255) not null unique,
                                 primary key (id)
);

create table tb_feature (
                            id bigint generated by default as identity,
                            code varchar(255) not null unique,
                            description varchar(255),
                            name varchar(255) not null,
                            primary key (id)
);

create table tb_role (
                         id bigint generated by default as identity,
                         authority varchar(50) not null unique,
                         primary key (id)
);

create table tb_user (
                         id bigint generated by default as identity,
                         email varchar(255) not null unique,
                         first_name varchar(255) not null,
                         last_name varchar(255) not null,
                         password varchar(255) not null,
                         primary key (id)
);

create table tb_billing_plan_feature (
                                         billing_plan_id bigint not null,
                                         feature_id bigint not null,
                                         primary key (billing_plan_id, feature_id),

                                         constraint fk_billing_plan_feature_plan
                                             foreign key (billing_plan_id)
                                                 references tb_billing_plan,

                                         constraint fk_billing_plan_feature_feature
                                             foreign key (feature_id)
                                                 references tb_feature
);

create table tb_user_role (
                              role_id bigint not null,
                              user_id bigint not null,
                              primary key (role_id, user_id),

                              constraint fk_user_role_role
                                  foreign key (role_id)
                                      references tb_role,

                              constraint fk_user_role_user
                                  foreign key (user_id)
                                      references tb_user
);

create table tb_condominium (
                                id bigint generated by default as identity,
                                is_active boolean not null,
                                billing_plan_id bigint not null,
                                address varchar(255) not null,
                                name varchar(255) not null,
                                primary key (id),

                                constraint fk_condominium_billing_plan
                                    foreign key (billing_plan_id)
                                        references tb_billing_plan
);

create table tb_condominium_user (
                                     id bigint generated by default as identity,
                                     condominium_id bigint not null,
                                     role_id bigint not null,
                                     user_id bigint not null,
                                     primary key (id),

                                     constraint fk_condominium_user_condominium
                                         foreign key (condominium_id)
                                             references tb_condominium,

                                     constraint fk_condominium_user_role
                                         foreign key (role_id)
                                             references tb_role,

                                     constraint fk_condominium_user_user
                                         foreign key (user_id)
                                             references tb_user
);

create table tb_sector (
                           id bigint generated by default as identity,
                           condominium_id bigint not null,
                           name varchar(255) not null,
                           structural_type varchar(255) not null,

                           primary key (id),

                           constraint uk_sector_condominium_name
                               unique (condominium_id, name),

                           constraint ck_sector_structural_type
                               check (
                                   structural_type in (
                                                       'BLOCK',
                                                       'STREET',
                                                       'COURT',
                                                       'GRILL'
                                       )
                                   ),

                           constraint fk_sector_condominium
                               foreign key (condominium_id)
                                   references tb_condominium
);

create table tb_unit (
                         id bigint generated by default as identity,
                         sector_id bigint not null,
                         identifier varchar(255) not null,

                         primary key (id),

                         constraint uk_unit_sector_identifier
                             unique (sector_id, identifier),

                         constraint fk_unit_sector
                             foreign key (sector_id)
                                 references tb_sector
);

create table tb_resident (
                             id bigint generated by default as identity,
                             unit_id bigint not null,
                             user_id bigint not null,
                             type varchar(255),

                             primary key (id),

                             constraint ck_resident_type
                                 check (
                                     type in (
                                              'TENANT',
                                              'DEPENDENT',
                                              'OWNER'
                                         )
                                     ),

                             constraint fk_resident_unit
                                 foreign key (unit_id)
                                     references tb_unit,

                             constraint fk_resident_user
                                 foreign key (user_id)
                                     references tb_user
);

create table tb_package (
                            id bigint generated by default as identity,
                            cancelled_at timestamp without time zone,
                            notified_at timestamp without time zone,
                            picked_up_at timestamp without time zone,
                            received_at timestamp without time zone,
                            returned_at timestamp without time zone,
                            recipient_id bigint not null,
                            unit_id bigint not null,
                            description varchar(255),
                            status varchar(255),

                            primary key (id),

                            constraint ck_package_status
                                check (
                                    status in (
                                               'EXPECTED',
                                               'RECEIVED',
                                               'NOTIFIED',
                                               'PICKED_UP',
                                               'CANCELLED',
                                               'RETURNED'
                                        )
                                    ),

                            constraint fk_package_recipient
                                foreign key (recipient_id)
                                    references tb_user,

                            constraint fk_package_unit
                                foreign key (unit_id)
                                    references tb_unit
);

create table tb_package_history (
                                    id bigint generated by default as identity,
                                    package_id bigint not null,
                                    performed_at timestamp(6) not null,
                                    performed_by_id bigint,
                                    notes varchar(500),
                                    actor_type varchar(255) not null,
                                    new_status varchar(255) not null,
                                    previous_status varchar(255),

                                    primary key (id),

                                    constraint ck_package_history_actor_type
                                        check (
                                            actor_type in (
                                                           'USER',
                                                           'SYSTEM',
                                                           'INTEGRATION'
                                                )
                                            ),

                                    constraint ck_package_history_new_status
                                        check (
                                            new_status in (
                                                           'EXPECTED',
                                                           'RECEIVED',
                                                           'NOTIFIED',
                                                           'PICKED_UP',
                                                           'CANCELLED',
                                                           'RETURNED'
                                                )
                                            ),

                                    constraint ck_package_history_previous_status
                                        check (
                                            previous_status is null
                                                or previous_status in (
                                                                       'EXPECTED',
                                                                       'RECEIVED',
                                                                       'NOTIFIED',
                                                                       'PICKED_UP',
                                                                       'CANCELLED',
                                                                       'RETURNED'
                                                )
                                            ),

                                    constraint fk_package_history_package
                                        foreign key (package_id)
                                            references tb_package,

                                    constraint fk_package_history_performed_by
                                        foreign key (performed_by_id)
                                            references tb_user
);

create table tb_notification (
                                 id bigint generated by default as identity,
                                 read boolean not null,
                                 created_at timestamp(6) not null,
                                 recipient_id bigint not null,
                                 message varchar(500) not null,
                                 title varchar(255) not null,
                                 type varchar(255) not null,

                                 primary key (id),

                                 constraint ck_notification_type
                                     check (
                                         type in (
                                                  'PACKAGE_RECEIVED',
                                                  'PACKAGE_STATUS_CHANGED',
                                                  'ANNOUNCEMENT',
                                                  'RESERVATION'
                                             )
                                         ),

                                 constraint fk_notification_recipient
                                     foreign key (recipient_id)
                                         references tb_user
);

create table tb_announcement (
                                 id bigint generated by default as identity,
                                 active boolean not null,
                                 condominium_id bigint not null,
                                 created_at timestamp(6) not null,
                                 created_by_id bigint not null,
                                 expires_at timestamp(6),
                                 title varchar(150) not null,
                                 content text not null,

                                 primary key (id),

                                 constraint fk_announcement_condominium
                                     foreign key (condominium_id)
                                         references tb_condominium,

                                 constraint fk_announcement_created_by
                                     foreign key (created_by_id)
                                         references tb_user
);

create table tb_common_area (
                                id bigint generated by default as identity,
                                active boolean not null,
                                capacity integer not null,
                                condominium_id bigint not null,
                                name varchar(120) not null,
                                description varchar(500),

                                primary key (id),

                                constraint fk_common_area_condominium
                                    foreign key (condominium_id)
                                        references tb_condominium
);

create table tb_reservation (
                                id bigint generated by default as identity,
                                cancelled_at timestamp(6),
                                common_area_id bigint not null,
                                created_at timestamp(6) not null,
                                end_at timestamp(6) not null,
                                reserved_by_id bigint not null,
                                start_at timestamp(6) not null,
                                status varchar(255) not null,

                                primary key (id),

                                constraint ck_reservation_status
                                    check (
                                        status in (
                                                   'CONFIRMED',
                                                   'CANCELLED'
                                            )
                                        ),

                                constraint fk_reservation_common_area
                                    foreign key (common_area_id)
                                        references tb_common_area,

                                constraint fk_reservation_reserved_by
                                    foreign key (reserved_by_id)
                                        references tb_user
);